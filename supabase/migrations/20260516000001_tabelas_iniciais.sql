 
-- 01_SCHEMA_PUBLIC.SQL
-- Criação completa do schema public: tipos, tabelas, índices e triggers.
-- Idempotente: pode ser re-corrido após o 00_RESET_COMPLETO.sql
 


 
-- 1. TIPOS ENUM
 

CREATE TYPE user_role         AS ENUM ('patient', 'doctor', 'receptionist', 'admin');
CREATE TYPE appointment_type  AS ENUM ('normal', 'urgent', 'follow_up');
CREATE TYPE appointment_status AS ENUM ('scheduled', 'completed', 'canceled', 'no_show');
CREATE TYPE queue_status      AS ENUM ('waiting', 'called', 'attended', 'absent');
CREATE TYPE invoice_status    AS ENUM ('pending', 'paid', 'canceled', 'refunded');
CREATE TYPE payment_method    AS ENUM ('cash', 'card', 'transfer', 'insurance');
CREATE TYPE document_type     AS ENUM ('analysis', 'prescription', 'invoice', 'other');


 
-- 2. FUNÇÃO TRIGGER PARA UPDATED_AT
 

CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


 
-- 3. TABELAS (sem password_hash — a auth é gerida pelo Supabase Auth)
 

CREATE TABLE specialties (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE insurances (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    contact_email VARCHAR(255)
);

-- users espelha o auth.users do Supabase.
-- O id é o mesmo UUID que auth.users.id.
-- Sem password_hash: a password é gerida exclusivamente pelo Supabase Auth.
CREATE TABLE users (
    id               UUID PRIMARY KEY,           -- = auth.users.id
    email            VARCHAR(255) UNIQUE NOT NULL,
    name             VARCHAR(255) NOT NULL,
    nif              VARCHAR(50)  UNIQUE,
    date_of_birth    DATE,
    phone            VARCHAR(50),
    address          TEXT,
    role             user_role NOT NULL,
    created_at       TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    last_login       TIMESTAMPTZ NULL DEFAULT NULL,
    accepted_terms_at TIMESTAMPTZ NULL DEFAULT NULL,
    deleted_at       TIMESTAMPTZ NULL DEFAULT NULL
);

CREATE TABLE patients (
    user_id       UUID PRIMARY KEY,
    health_number VARCHAR(100) UNIQUE NOT NULL,
    insurance_id  INTEGER NULL,
    FOREIGN KEY (user_id)      REFERENCES users(id)      ON DELETE CASCADE,
    FOREIGN KEY (insurance_id) REFERENCES insurances(id)
);

CREATE TABLE doctors (
    user_id                 UUID PRIMARY KEY,
    specialty_id            INT NOT NULL,
    license_number          VARCHAR(100) UNIQUE NOT NULL,
    default_slot_duration_min INT NOT NULL DEFAULT 30,
    FOREIGN KEY (user_id)      REFERENCES users(id)        ON DELETE CASCADE,
    FOREIGN KEY (specialty_id) REFERENCES specialties(id)
);

CREATE TABLE user_preferences (
    user_id               UUID PRIMARY KEY,
    email_notifications   BOOLEAN DEFAULT TRUE,
    push_notifications    BOOLEAN DEFAULT TRUE,
    reminder_24h          BOOLEAN DEFAULT TRUE,
    appointment_alerts    BOOLEAN DEFAULT TRUE,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE appointments (
    id             UUID PRIMARY KEY,
    patient_id     UUID NOT NULL,
    doctor_id      UUID NOT NULL,
    scheduled_date DATE NOT NULL,
    scheduled_time TIME NOT NULL,
    duration_min   INT  NOT NULL DEFAULT 30,
    type           appointment_type   NOT NULL,
    status         appointment_status NOT NULL,
    patient_notes  TEXT,
    diagnosis_notes TEXT,
    created_by     UUID,
    created_at     TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    deleted_at     TIMESTAMPTZ NULL DEFAULT NULL,
    FOREIGN KEY (patient_id) REFERENCES patients(user_id),
    FOREIGN KEY (doctor_id)  REFERENCES doctors(user_id),
    FOREIGN KEY (created_by) REFERENCES users(id)
);

CREATE TABLE virtual_queue (
    id              UUID PRIMARY KEY,
    ticket_number   VARCHAR(50) NOT NULL,
    appointment_id  UUID NULL,
    patient_id      UUID NOT NULL,
    doctor_id       UUID NOT NULL,
    status          queue_status NOT NULL DEFAULT 'waiting',
    queue_position  INT  NOT NULL,
    issued_at       TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    called_at       TIMESTAMPTZ NULL DEFAULT NULL,
    attended_at     TIMESTAMPTZ NULL DEFAULT NULL,
    CONSTRAINT chk_queue_patient_or_appt CHECK (
        appointment_id IS NOT NULL OR (patient_id IS NOT NULL AND doctor_id IS NOT NULL)
    ),
    FOREIGN KEY (appointment_id) REFERENCES appointments(id),
    FOREIGN KEY (patient_id)     REFERENCES patients(user_id),
    FOREIGN KEY (doctor_id)      REFERENCES doctors(user_id)
);

CREATE TABLE doctor_availability (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id        UUID NOT NULL,
    day_of_week      SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    start_time       TIME NOT NULL,
    end_time         TIME NOT NULL,
    slot_duration_min INT NOT NULL,
    CONSTRAINT chk_availability_times CHECK (end_time > start_time),
    FOREIGN KEY (doctor_id) REFERENCES doctors(user_id) ON DELETE CASCADE
);

CREATE TABLE blocked_slots (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id      UUID NOT NULL,
    start_datetime TIMESTAMPTZ NOT NULL,
    end_datetime   TIMESTAMPTZ NOT NULL,
    reason         TEXT,
    created_at     TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_blocked_times CHECK (end_datetime > start_datetime),
    FOREIGN KEY (doctor_id) REFERENCES doctors(user_id) ON DELETE CASCADE
);

CREATE TABLE invoices (
    id             UUID PRIMARY KEY,
    appointment_id UUID,
    patient_id     UUID NOT NULL,
    insurance_id   INTEGER NULL,
    amount         DECIMAL(10,2) NOT NULL,
    tax_amount     DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    status         invoice_status NOT NULL DEFAULT 'pending',
    payment_method payment_method NULL,
    issued_at      TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    paid_at        TIMESTAMPTZ NULL DEFAULT NULL,
    notes          TEXT,
    created_by     UUID,
    FOREIGN KEY (appointment_id) REFERENCES appointments(id),
    FOREIGN KEY (patient_id)     REFERENCES patients(user_id),
    FOREIGN KEY (insurance_id)   REFERENCES insurances(id),
    FOREIGN KEY (created_by)     REFERENCES users(id)
);

CREATE TABLE documents (
    id               UUID PRIMARY KEY,
    patient_id       UUID NOT NULL,
    doctor_id        UUID NULL,
    appointment_id   UUID NULL,
    invoice_id       UUID NULL,
    type             document_type NOT NULL,
    name             VARCHAR(255) NOT NULL,
    laboratory_name  VARCHAR(255) NULL,
    file_path        TEXT NOT NULL,
    file_size_bytes  BIGINT NOT NULL,
    uploaded_by      UUID,
    created_at       TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    deleted_at       TIMESTAMPTZ NULL DEFAULT NULL,
    FOREIGN KEY (patient_id)     REFERENCES patients(user_id),
    FOREIGN KEY (doctor_id)      REFERENCES doctors(user_id),
    FOREIGN KEY (appointment_id) REFERENCES appointments(id),
    FOREIGN KEY (invoice_id)     REFERENCES invoices(id),
    FOREIGN KEY (uploaded_by)    REFERENCES users(id)
);

CREATE TABLE notifications (
    id         UUID PRIMARY KEY,
    user_id    UUID NOT NULL,
    type       VARCHAR(50) NOT NULL,
    message    TEXT NOT NULL,
    is_read    BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE audit_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id       UUID,
    action         VARCHAR(255) NOT NULL,
    target_user_id UUID,
    target_type    VARCHAR(50),
    description    TEXT,
    created_at     TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (actor_id)       REFERENCES users(id),
    FOREIGN KEY (target_user_id) REFERENCES users(id)
);

CREATE TABLE clinic_settings (
    setting_key   VARCHAR(100) PRIMARY KEY,
    setting_value TEXT NOT NULL,
    description   TEXT,
    updated_at    TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by    UUID,
    FOREIGN KEY (updated_by) REFERENCES users(id)
);


 
-- 4. ÍNDICES DE PERFORMANCE
 

CREATE INDEX idx_appointments_scheduled_date ON appointments(scheduled_date);
CREATE INDEX idx_appointments_status         ON appointments(status);
CREATE INDEX idx_appointments_patient_id     ON appointments(patient_id);
CREATE INDEX idx_appointments_doctor_id      ON appointments(doctor_id);
CREATE INDEX idx_virtual_queue_status        ON virtual_queue(status);
CREATE INDEX idx_virtual_queue_doctor_id     ON virtual_queue(doctor_id);
CREATE INDEX idx_users_role                  ON users(role);
CREATE INDEX idx_users_deleted_at            ON users(deleted_at);
CREATE INDEX idx_notifications_user_id       ON notifications(user_id);
CREATE INDEX idx_documents_patient_id        ON documents(patient_id);
CREATE INDEX idx_invoices_patient_id         ON invoices(patient_id);
CREATE INDEX idx_invoices_status             ON invoices(status);


 
-- 5. TRIGGERS
 

CREATE TRIGGER set_timestamp_appointments
BEFORE UPDATE ON appointments
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER set_timestamp_clinic_settings
BEFORE UPDATE ON clinic_settings
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();


